import Foundation
import ImageIO

@MainActor
final class LocalInspectionPhotoStore: InspectionPhotoStoring {
    private let directory: URL

    init(directory: URL? = nil) throws {
        if let directory {
            self.directory = directory
        } else {
            let applicationSupport = try FileManager.default.url(
                for: .applicationSupportDirectory,
                in: .userDomainMask,
                appropriateFor: nil,
                create: true
            )

            self.directory = applicationSupport
                .appendingPathComponent("CellMate", isDirectory: true)
                .appendingPathComponent(
                    "InspectionPhotos",
                    isDirectory: true
                )
        }
    }

    func savePhoto(
        imageData: Data
    ) async throws -> Inspection.PhotoEvidence {
        let id = UUID()
        let filename = "\(id.uuidString).jpg"
        let fileURL = try validatedURL(for: filename)
        let directory = self.directory
        let capturedAt = Date()

        try await Task.detached(priority: .userInitiated) {
            try Self.writePhoto(
                imageData,
                to: fileURL,
                directory: directory
            )
        }.value

        return Inspection.PhotoEvidence(
            id: id,
            filename: filename,
            capturedAt: capturedAt
        )
    }

    func loadPhoto(filename: String) async throws -> Data {
        let fileURL = try validatedURL(for: filename)

        return try await Task.detached(priority: .userInitiated) {
            try Task.checkCancellation()

            guard FileManager.default.fileExists(
                atPath: fileURL.path
            ) else {
                throw InspectionPhotoStorageError.photoNotFound
            }

            do {
                return try Data(contentsOf: fileURL)
            } catch {
                throw InspectionPhotoStorageError.readFailed
            }
        }.value
    }

    func deletePhoto(filename: String) async throws {
        let fileURL = try validatedURL(for: filename)

        try await Task.detached(priority: .utility) {
            try Task.checkCancellation()

            let manager = FileManager.default

            guard manager.fileExists(atPath: fileURL.path) else {
                return
            }

            do {
                try manager.removeItem(at: fileURL)
            } catch {
                // Another cleanup may already have removed it.
                guard manager.fileExists(atPath: fileURL.path) else {
                    return
                }

                throw InspectionPhotoStorageError.deleteFailed
            }
        }.value
    }

    private func validatedURL(for filename: String) throws -> URL {
        // Accept only filenames generated by this store.
        // This also rejects absolute paths and directory traversal.
        guard filename.hasSuffix(".jpg") else {
            throw InspectionPhotoStorageError.invalidFilename
        }

        let identifier = String(filename.dropLast(4))

        guard let id = UUID(uuidString: identifier),
              filename == "\(id.uuidString).jpg" else {
            throw InspectionPhotoStorageError.invalidFilename
        }

        return directory.appendingPathComponent(
            filename,
            isDirectory: false
        )
    }

    nonisolated private static func writePhoto(
        _ data: Data,
        to fileURL: URL,
        directory: URL
    ) throws {
        try Task.checkCancellation()

        // A bounded input size prevents unusually large imports.
        let maximumInputBytes = 20 * 1_024 * 1_024

        guard !data.isEmpty else {
            throw InspectionPhotoStorageError.invalidImage
        }

        guard data.count <= maximumInputBytes else {
            throw InspectionPhotoStorageError.imageTooLarge
        }

        let sourceOptions: [CFString: Any] = [
            kCGImageSourceShouldCache: false
        ]

        guard let source = CGImageSourceCreateWithData(
            data as CFData,
            sourceOptions as CFDictionary
        ) else {
            throw InspectionPhotoStorageError.invalidImage
        }

        let thumbnailOptions: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 1_600,
            kCGImageSourceShouldCacheImmediately: true
        ]

        guard let image = CGImageSourceCreateThumbnailAtIndex(
            source,
            0,
            thumbnailOptions as CFDictionary
        ) else {
            throw InspectionPhotoStorageError.invalidImage
        }

        let output = NSMutableData()

        guard let destination = CGImageDestinationCreateWithData(
            output,
            "public.jpeg" as CFString,
            1,
            nil
        ) else {
            throw InspectionPhotoStorageError.saveFailed
        }

        let outputOptions: [CFString: Any] = [
            kCGImageDestinationLossyCompressionQuality: 0.85
        ]

        // Encode the rendered image without copying the source's
        // EXIF or GPS metadata.
        CGImageDestinationAddImage(
            destination,
            image,
            outputOptions as CFDictionary
        )

        guard CGImageDestinationFinalize(destination) else {
            throw InspectionPhotoStorageError.saveFailed
        }

        try Task.checkCancellation()

        do {
            try FileManager.default.createDirectory(
                at: directory,
                withIntermediateDirectories: true,
                attributes: nil
            )

            try (output as Data).write(
                to: fileURL,
                options: [.atomic, .completeFileProtectionUnlessOpen]
            )
        } catch {
            throw InspectionPhotoStorageError.saveFailed
        }
    }
}
